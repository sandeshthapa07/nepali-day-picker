// Encodes data/bs-calendar.json into src/data/table.ts.
// Each month is stored as (length - 29) in 2 bits, so one BS year fits in 24 bits.
// Usage: node scripts/build-data.mjs [--check]
//   --check  exit 1 if src/data/table.ts is out of date (used in CI)
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
const json = JSON.parse(readFileSync(new URL("data/bs-calendar.json", root), "utf8"));
const target = fileURLToPath(new URL("src/data/table.ts", root));

const years = json.years;
const first = years[0].year;
years.forEach((row, i) => {
  if (row.year !== first + i) throw new Error(`Years must be consecutive: expected ${first + i}, got ${row.year}`);
  if (row.months.length !== 12) throw new Error(`${row.year}: expected 12 months`);
  for (const len of row.months) {
    if (!Number.isInteger(len) || len < 29 || len > 32)
      throw new Error(`${row.year}: month length ${len} is outside 29-32`);
  }
  const total = row.months.reduce((a, b) => a + b, 0);
  if (total !== 365 && total !== 366) throw new Error(`${row.year}: year has ${total} days`);
});

const encoded = years.map((row) => row.months.reduce((acc, len, m) => acc | ((len - 29) << (2 * m)), 0));
const [ey, em, ed] = json.epoch.ad.split("-").map(Number);
const disputed = years.filter((r) => r.status === "disputed").map((r) => r.year);
const singleSource = years.filter((r) => r.status === "single-source").map((r) => r.year);

const chunks = [];
for (let i = 0; i < encoded.length; i += 10) chunks.push(`  ${encoded.slice(i, i + 10).join(", ")},`);

const out = `// Generated by scripts/build-data.mjs from data/bs-calendar.json. Do not edit by hand.

/** First BS year in the table. */
export const FIRST_YEAR = ${first};
/** Last BS year in the table. */
export const LAST_YEAR = ${years.at(-1).year};
/** Day number 0: BS ${json.epoch.bs} = AD ${json.epoch.ad}, as a UTC timestamp. */
export const EPOCH_UTC = ${Date.UTC(ey, em - 1, ed)};
/** First BS year whose month lengths are projections, not published by the calendar committee. */
export const PROJECTED_FROM = ${json.projectedFrom};
/** Years where the sources disagree on month lengths (year totals agree). */
export const DISPUTED_YEARS: readonly number[] = [${disputed.join(", ")}];
/** Years backed by only one source. */
export const SINGLE_SOURCE_YEARS: readonly number[] = [${singleSource.join(", ")}];

/** One entry per BS year from FIRST_YEAR; month m (0-11) has 29 + ((value >> 2m) & 3) days. */
export const ENCODED_MONTHS: readonly number[] = [
${chunks.join("\n")}
];
`;

if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8").replace(/\r\n/g, "\n");
  if (current !== out) {
    console.error("src/data/table.ts is out of date. Run: npm run data");
    process.exit(1);
  }
  console.log("src/data/table.ts is up to date.");
} else {
  writeFileSync(target, out);
  console.log(`Wrote ${encoded.length} years (${first}-${years.at(-1).year}) to src/data/table.ts`);
}
